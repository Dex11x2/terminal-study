const NAME_TABS = ['bash','zsh','cmd','ps','git','docker','vps','files','wsl','start','tools','sshc','nginx','pg','mongo','node','python','net','diag','sec','cloud','gha','os'];

/* معنى اسم الدرس: لكل جزء في الاسم (مفصول بـ « / » أو « و » أو « , ») */
function cmdNameNotes(tab, cmd){
  if (!NAME_TABS.includes(tab)) return [];
  const out = [], seen = new Set();
  for (const part of String(cmd).split(/\s+\/\s+|\s+و\s+|,\s*/)) {
    const w = part.trim().split(/\s+/)[0].replace(/[()]/g, '');
    if (!w || seen.has(w)) continue;
    seen.add(w);
    const tabMap = CMD_NAMES_TAB[tab] || {};
    let note = tabMap[w] || CMD_NAMES[w] || CMD_NAMES[w.toLowerCase()];
    const ps = !note && /^([A-Z][a-z]+(?:To|From)?)-([A-Za-z0-9]+)$/.exec(w);
    if (ps && PS_VERBS[ps[1]]) note = '**'+ps[1]+'** = '+PS_VERBS[ps[1]] + (PS_NOUNS[ps[2]] ? '، و **'+ps[2]+'** = '+PS_NOUNS[ps[2]] : '');
    if (note) out.push([w, note]);
    if (out.length === 3) break;
  }
  return out;
}
